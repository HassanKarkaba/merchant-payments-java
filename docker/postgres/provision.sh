#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" -v database="$POSTGRES_DB" -v owner="$DB_OWNER_USER" -v owner_password="$DB_OWNER_PASSWORD" -v runtime="$DB_RUNTIME_USER" -v runtime_password="$DB_RUNTIME_PASSWORD" -v purge="$DB_PURGE_USER" -v purge_password="$DB_PURGE_PASSWORD" <<'SQL'
CREATE ROLE :"owner" LOGIN PASSWORD :'owner_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE :"runtime" LOGIN PASSWORD :'runtime_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE :"purge" LOGIN PASSWORD :'purge_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE TEMPORARY ON DATABASE :"database" FROM PUBLIC;
GRANT ALL ON SCHEMA public TO :"owner";
GRANT USAGE ON SCHEMA public TO :"runtime";
SQL
